import { test } from 'node:test';
import assert from 'node:assert/strict';
import sax from 'sax';
import { PDFDocument } from 'pdf-lib';
import { createProject, createFloor, addRectRoom, addOpening, addFurniture, roomEdgeWalls, setWallLength, floorMetrics } from '../../geometry/src/index';
import { buildDrawing, toSVG, toDXF, parseDXF, planToPdf, toGLB, readGLB, toOBJ, roomsCSV, projectJSON, readProjectJSON, pageSizePt, chooseScale } from '../src/index';
import { buildFloorMesh } from '../../renderer-3d/src/mesh';
import { parseProject } from '../../geometry/src/index';
import type { Project } from '../../shared-types/src/index';

function sample(): Project {
  let f = createFloor('Floor 1');
  const r1 = addRectRoom(f, { x: 0, y: 0, width: 4, length: 3.5, height: 2.75, name: 'Living' }); f = r1.floor;
  const r2 = addRectRoom(f, { x: 4, y: 0, width: 3, length: 3.5, name: 'סלון' }); f = r2.floor;
  const walls = roomEdgeWalls(f, f.rooms[r1.roomId]);
  f = addOpening(f, walls[0]!.id, 'window', 2, { width: 1.2 }).floor;
  const shared = Object.values(f.walls).find((w) => !w.exterior)!;
  f = addOpening(f, shared.id, 'door', 1.75, { width: 0.8 }).floor;
  f = addFurniture(f, { catalogId: 'sofa-3', name: 'Sofa', category: 'living', x: 2, y: 2.8, rotation: 180, width: 2.1, depth: 0.9, height: 0.85, elevation: 0, mirrored: false, layer: 'furniture', color: '#7d8597', meta: { shape: 'sofa' } }).floor;
  f = addFurniture(f, { catalogId: 'dining-table', name: 'Table', category: 'living', x: 5.5, y: 1.75, rotation: 0, width: 1.6, depth: 0.9, height: 0.75, elevation: 0, mirrored: false, layer: 'furniture', color: '#a47551', meta: { shape: 'table' } }).floor;
  const p = createProject('My Apartment', { address: 'Herzl 1, Tel Aviv' });
  return { ...p, floors: [f] };
}

test('drawing list contains walls with door/window gaps, arcs and dimensions', () => {
  const p = sample();
  const prims = buildDrawing(p.floors[0], { unit: 'm', precision: 2 });
  assert.ok(prims.filter((x) => x.t === 'poly' && x.layer === 'walls').length >= 9, 'wall bodies split at openings');
  assert.equal(prims.filter((x) => x.t === 'arc').length, 1);
  const dims = prims.filter((x) => x.t === 'dim').map((x) => (x as { text: string }).text);
  assert.ok(dims.includes('4.00 m') && dims.includes('3.50 m') && dims.includes('3.00 m'));
  const texts = prims.filter((x) => x.t === 'text').map((x) => (x as { text: string }).text);
  assert.ok(texts.includes('14.00 m²') && texts.includes('10.50 m²'));
});

test('SVG is well-formed XML, scaled in mm, contains labels', () => {
  const svg = toSVG(buildDrawing(sample().floors[0], { unit: 'm', precision: 2 }), { title: 'My Apartment' });
  const parser = sax.parser(true);
  let elements = 0, err: Error | null = null;
  parser.onopentag = () => { elements++; };
  parser.onerror = (e: Error) => { err = e; };
  parser.write(svg).close();
  assert.equal(err, null);
  assert.ok(elements > 30);
  assert.match(svg, /width="[\d.]+mm"/);
  assert.ok(svg.includes('14.00 m²') && svg.includes('סלון'));
});

test('DXF parses, has layers and real-world coordinates (Y flipped, not mirrored)', () => {
  const dxf = toDXF(buildDrawing(sample().floors[0], { unit: 'm', precision: 2 }));
  const ents = parseDXF(dxf);
  const layers = new Set(ents.map((e) => e.layer));
  for (const l of ['WALLS', 'DOORS', 'WINDOWS', 'DIMENSIONS', 'TEXT', 'ROOMS', 'FURNITURE']) assert.ok(layers.has(l), l);
  assert.ok(ents.some((e) => e.type === 'ARC'));
  const texts = ents.filter((e) => e.type === 'TEXT').map((e) => e.data[1][0]);
  assert.ok(texts.includes('4.00 m'));
  assert.ok(texts.some((t) => t.includes('\\U+05E1')), 'Hebrew encoded as \\U+ escapes');
  const xs = ents.filter((e) => e.type === 'VERTEX' && e.layer === 'ROOMS').map((e) => Number(e.data[10][0]));
  const ys = ents.filter((e) => e.type === 'VERTEX' && e.layer === 'ROOMS').map((e) => Number(e.data[20][0]));
  assert.equal(Math.min(...xs), 0); assert.equal(Math.max(...xs), 7);
  assert.equal(Math.max(...ys), 0); assert.equal(Math.min(...ys), -3.5);
});

test('PDF: valid document, true scale, text extractable', async () => {
  const p = sample();
  const bytes = await planToPdf(p, { paper: 'A4', orientation: 'landscape', scale: 'fit', header: 'Survey', footer: 'Generated by PlanForge' });
  const doc = await PDFDocument.load(bytes);
  assert.equal(doc.getPageCount(), 2);
  const { width: w, height: h } = doc.getPage(0).getSize();
  const [ew, eh] = pageSizePt({ paper: 'A4', orientation: 'landscape' });
  assert.ok(Math.abs(w - ew) < 0.01 && Math.abs(h - eh) < 0.01 && w > h);
  const pdfjs = await import('pdfjs-dist/legacy/build/pdf.mjs');
  const loaded = await pdfjs.getDocument({ data: new Uint8Array(bytes), verbosity: 0 }).promise;
  const page = await loaded.getPage(1);
  const tc = await page.getTextContent();
  const text = tc.items.map((i) => ('str' in i ? i.str : '')).join(' ');
  assert.ok(text.includes('My Apartment'), text);
  assert.ok(text.includes('14.00 m'), 'room area printed');
  assert.ok(text.includes('4.00 m'), 'wall dimension printed');
  assert.match(text, /Scale: 1:(50|75|100)/);
  assert.equal(chooseScale(7.9, 4.4, 750, 450), 50);
});

test('GLB: valid container, consistent accessors, correct bounds', () => {
  const parts = buildFloorMesh(sample().floors[0]);
  const glb = toGLB(parts);
  const { json, bin } = readGLB(glb);
  assert.equal(json.asset.version, '2.0');
  for (const a of json.accessors) {
    const bv = json.bufferViews[a.bufferView];
    const size = (a.type === 'VEC3' ? 3 : 1) * 4;
    assert.equal(bv.byteLength, a.count * size);
    assert.ok(bv.byteOffset + bv.byteLength <= bin.byteLength);
    if (a.componentType === 5125) {
      const idx = new Uint32Array(bin.buffer.slice(bin.byteOffset + bv.byteOffset, bin.byteOffset + bv.byteOffset + bv.byteLength));
      const posAcc = json.accessors[json.accessors.indexOf(a) - 2];
      assert.ok(Math.max(...idx) < posAcc.count);
    }
  }
  const walls = json.accessors.filter((_: unknown, i: number) => i % 3 === 0);
  const maxY = Math.max(...walls.map((a: { max: number[] }) => a.max[1]));
  const minX = Math.min(...walls.map((a: { min: number[] }) => a.min[0]));
  const maxX = Math.max(...walls.map((a: { max: number[] }) => a.max[0]));
  assert.ok(Math.abs(maxY - 2.75) < 1e-5, `height ${maxY}`);
  assert.ok(Math.abs(minX + 0.075) < 1e-5 && Math.abs(maxX - 7.075) < 1e-5);
});

test('3D walls have holes: window and door spans are open', () => {
  const f = sample().floors[0];
  const parts = buildFloorMesh(f);
  const win = Object.values(f.openings).find((o) => o.kind === 'window')!;
  const wall = parts.find((p) => p.kind === 'wall' && p.id === win.wallId)!;
  // no wall triangle vertex strictly inside the window aperture (x in (1.4, 2.6), y in (0.9, 2.1)) on y=0 plane
  for (let i = 0; i < wall.positions.length; i += 3) {
    const [x, y] = [wall.positions[i], wall.positions[i + 1]];
    assert.ok(!(x > 1.41 && x < 2.59 && y > 0.91 && y < 2.09));
  }
  assert.ok(parts.some((p) => p.kind === 'glass') && parts.some((p) => p.kind === 'door') && parts.some((p) => p.kind === 'furniture'));
});

test('OBJ references valid vertices; CSV and JSON roundtrip', () => {
  const p = sample();
  const { obj, mtl } = toOBJ(buildFloorMesh(p.floors[0]));
  const v = obj.split('\n').filter((l) => l.startsWith('v ')).length;
  const maxRef = Math.max(...obj.split('\n').filter((l) => l.startsWith('f ')).flatMap((l) => l.slice(2).split(' ').map((t) => Number(t.split('//')[0]))));
  assert.ok(maxRef <= v && v > 100);
  assert.match(mtl, /newmtl m_/);
  const csv = roomsCSV(p);
  assert.ok(csv.startsWith('﻿') && csv.includes('Living,14.000'));
  const back = parseProject(readProjectJSON(projectJSON(p)));
  assert.equal(floorMetrics(back.floors[0]).grossArea.toFixed(2), '24.50');
});

test('exports update after an edit (single source of truth)', () => {
  const p = sample();
  const f = p.floors[0];
  const living = Object.values(f.rooms).find((r) => r.name === 'Living')!;
  const top = roomEdgeWalls(f, living)[0]!;
  const g = setWallLength(f, top.id, 4.5, 'a');
  const dims = buildDrawing(g, { unit: 'm', precision: 2 }).filter((x) => x.t === 'dim').map((x) => (x as { text: string }).text);
  assert.ok(dims.includes('4.50 m'));
  assert.ok(toSVG(buildDrawing(g, { unit: 'm', precision: 2 })).includes('15.75 m²'));
});
