// Generates docs/export-examples/* from a clearly labelled DEMO project (run: node --import tsx scripts/export-examples.ts)
import { mkdirSync, writeFileSync } from 'node:fs';
import { createFloor, addRectRoom, addOpening, addFurniture, roomEdgeWalls, createProject } from '../packages/geometry/src/index';
import { buildDrawing, toSVG, toDXF, planToPdf, toGLB, toOBJ, roomsCSV, projectJSON } from '../packages/cad-io/src/index';
import { buildProjectMesh } from '../packages/renderer-3d/src/mesh';
import { catalogById } from '../packages/shared-types/src/catalog';

let f = createFloor('Floor 1');
const a = addRectRoom(f, { x: 0, y: 0, width: 4, length: 3.5, height: 2.75, name: 'Living' }); f = a.floor;
const b = addRectRoom(f, { x: 4, y: 0, width: 3, length: 3.5, name: 'Kitchen' }); f = b.floor;
f = addOpening(f, roomEdgeWalls(f, f.rooms[a.roomId])[0]!.id, 'window', 2, { width: 1.2 }).floor;
f = addOpening(f, Object.values(f.walls).find((w) => !w.exterior)!.id, 'door', 1.75, { width: 0.8 }).floor;
for (const [id, x, y, r] of [['sofa-3', 2, 2.85, 180], ['dining-table', 5.5, 1.75, 0]] as const) {
  const it = catalogById(id)!;
  f = addFurniture(f, { catalogId: id, name: it.name.en, category: it.category, x, y, rotation: r, width: it.width, depth: it.depth, height: it.height, elevation: 0, mirrored: false, layer: 'furniture', color: it.color, meta: { shape: it.shape } }).floor;
}
const p = { ...createProject('DEMO — My Apartment', { isDemo: true, address: 'Demo content (not user data)' }), floors: [f] };
const out = 'docs/export-examples';
mkdirSync(out, { recursive: true });
const prims = buildDrawing(f, { unit: 'm', precision: 2 });
writeFileSync(`${out}/demo-plan.svg`, toSVG(prims, { title: p.name }));
writeFileSync(`${out}/demo-plan.dxf`, toDXF(prims));
writeFileSync(`${out}/demo-model.glb`, toGLB(buildProjectMesh(p)));
const { obj, mtl } = toOBJ(buildProjectMesh(p), 'demo-model'); writeFileSync(`${out}/demo-model.obj`, obj); writeFileSync(`${out}/demo-model.mtl`, mtl);
writeFileSync(`${out}/demo-rooms.csv`, roomsCSV(p));
writeFileSync(`${out}/demo-project.planforge.json`, projectJSON(p));
writeFileSync(`${out}/demo-plan.pdf`, await planToPdf(p, { paper: 'A4', orientation: 'landscape', scale: 'fit', header: 'DEMO CONTENT', footer: 'Generated by PlanForge Studio export engine' }));
console.log('written to', out);
